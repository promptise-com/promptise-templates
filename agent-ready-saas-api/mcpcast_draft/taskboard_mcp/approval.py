"""Human approval for the taskboard tools that change data.

Generated by `promptise mcpcast` from openapi.json (profile full, auth api-key).
Regenerate after editing mcpcast.plan.yaml:

    promptise mcpcast mcpcast.plan.yaml

Gated calls wait in a pending store until a *different* human of the same tenant,
holding the 'approver' role, decides through approvals_list / approvals_decide.
Denied on timeout. The store holds at most MAX_PENDING calls, MAX_PENDING_PER_TENANT
per tenant and MAX_PENDING_PER_CLIENT per client; beyond a cap a call is denied at
once.
"""

from __future__ import annotations

from typing import Any

from promptise.mcp.server import (
    ApprovalGateMiddleware,
    HasRole,
    MCPServer,
    PendingApprover,
    RequestContext,
    ToolError,
)

from .config import (
    APPROVAL_TIMEOUT,
    GATED_TOOLS,
    MAX_PENDING,
    MAX_PENDING_PER_CLIENT,
    MAX_PENDING_PER_TENANT,
)


def install_approval_gate(server: MCPServer, approval_handler: Any | None = None) -> None:
    """Gate every tool declared with requires_approval=True.

    Args:
        server: The server being built.
        approval_handler: Override the approver (evaluations and tests inject
            an auto-approver or a denier); None installs the plan's mode.
    """
    if not GATED_TOOLS:
        return
    if approval_handler is None:
        # Capacity is bounded per tenant and per client as well as for the
        # whole store: one tenant's agent looping on a gated tool — or one
        # tenant spreading its calls over many API keys — must not fill the
        # store and get every other tenant's calls denied.
        approver = PendingApprover(
            server=None,
            approver_role="approver",
            max_pending=MAX_PENDING,
            max_pending_per_tenant=MAX_PENDING_PER_TENANT,
            max_pending_per_client=MAX_PENDING_PER_CLIENT,
        )
        register_tenant_scoped_approvals(server, approver)
        approval_handler = approver
    server.add_middleware(ApprovalGateMiddleware(approval_handler, timeout=APPROVAL_TIMEOUT))


def register_tenant_scoped_approvals(server: MCPServer, approver: PendingApprover) -> None:
    """Four-eyes review scoped to the reviewer's tenant.

    A reviewer only sees and decides calls made by their own tenant, and may
    never approve their own request.  (The SDK's stock admin tools are
    server-wide; in a multi-tenant server that would leak one tenant's
    arguments to another's reviewers.)
    """

    @server.tool(
        name="approvals_list",
        description="List this tenant's tool calls awaiting human approval.",
        auth=True,
        guards=[HasRole("approver")],
        tags=["approvals"],
    )
    async def approvals_list(ctx: RequestContext) -> list[dict[str, Any]]:
        tenant = getattr(ctx.client, "tenant_id", None)
        return [p for p in approver.pending() if p.get("tenant_id") == tenant]

    @server.tool(
        name="approvals_decide",
        description="Approve or deny one of this tenant's pending tool calls by request id.",
        auth=True,
        guards=[HasRole("approver")],
        tags=["approvals"],
    )
    async def approvals_decide(
        ctx: RequestContext, request_id: str, approve: bool, reason: str = ""
    ) -> dict[str, Any]:
        tenant = getattr(ctx.client, "tenant_id", None)
        entry = next((p for p in approver.pending() if p["request_id"] == request_id), None)
        if entry is None or entry.get("tenant_id") != tenant:
            raise ToolError(
                f"No pending request {request_id!r} for tenant {tenant!r}", code="NOT_FOUND"
            )
        if entry.get("client_id") == ctx.client_id:
            raise ToolError("A caller may not approve their own request", code="ACCESS_DENIED")
        resolved = approver.decide(
            request_id, approve, reviewer_id=ctx.client_id, reason=reason or None
        )
        return {"request_id": request_id, "approved": approve, "resolved": resolved}
