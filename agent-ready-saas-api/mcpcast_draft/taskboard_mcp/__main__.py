"""Command line for the taskboard MCP server.

Generated by `promptise mcpcast` from openapi.json (profile full, auth api-key).
Regenerate after editing mcpcast.plan.yaml:

    promptise mcpcast mcpcast.plan.yaml

    python -m taskboard_mcp                    # stdio: Claude Desktop, Cursor, Claude Code
    python -m taskboard_mcp --transport http   # http://127.0.0.1:8080/mcp
    taskboard-mcp --transport http             # the same, once `pip install .` ran
"""

from __future__ import annotations

import argparse

from promptise.mcp.server import MCPServer
from promptise.models import load_dotenv_if_present

from .config import SERVER_NAME
from .server import build_server


def run(server: MCPServer, argv: list[str] | None = None) -> None:
    """Serve *server* over stdio (default), HTTP or SSE, per the command line."""
    parser = argparse.ArgumentParser(description=f"{SERVER_NAME} MCP server")
    parser.add_argument("--transport", choices=["stdio", "http", "sse"], default="stdio")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8080)
    args = parser.parse_args(argv)
    server.run(transport=args.transport, host=args.host, port=args.port)


def main(argv: list[str] | None = None) -> None:
    """Build the server and serve it — the console script entry point.

    Reads the .env of the working directory (or a parent) first, so that `python -m
    taskboard_mcp` and `taskboard-mcp` see the same file as `docker run --env-file
    .env`. A variable already set in the environment wins; PROMPTISE_NO_DOTENV=1
    skips the file. build_server() itself never reads it: tests, evaluations and
    `promptise serve` configure the environment their own way.
    """
    load_dotenv_if_present()
    run(build_server(), argv)


if __name__ == "__main__":
    main()
