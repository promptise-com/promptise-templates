"""The HTTP client that calls the taskboard API on behalf of every tool.

Generated by `promptise mcpcast` from openapi.json (profile full, auth api-key).
Regenerate after editing mcpcast.plan.yaml:

    promptise mcpcast mcpcast.plan.yaml

Routes describe where each argument travels (path, query, body), and
advertise puts each parameter's JSON Schema from the plan into the tool's
input schema. Upstream adds the credential for the configured auth mode
where the API expects it, bounds every call by a wall-clock deadline, caps
the response, scrubs the credential from every body before the agent sees
it and maps failures to structured ToolError codes (UPSTREAM_AUTH_MISSING,
UPSTREAM_AUTH_INVALID, UPSTREAM_INSECURE, UPSTREAM_TIMEOUT,
UPSTREAM_UNREACHABLE, UPSTREAM_ERROR, UPSTREAM_RESPONSE_TOO_LARGE).
"""

from __future__ import annotations

import asyncio
import copy
import ipaddress
import json
import os
from collections.abc import Callable
from dataclasses import dataclass
from typing import Annotated, Any, TypeVar, get_type_hints
from urllib.parse import quote, urlsplit

import httpx
from promptise.mcp.server import RequestContext, ToolError
from pydantic import Field

from .config import (
    ALLOW_INSECURE_HTTP,
    AUTH_MODE,
    BASE_URL,
    CREDENTIAL_LOCATION,
    CREDENTIAL_NAME,
    DEFAULT_BASE_URL,
    ERROR_EXCERPT_CHARS,
    MAX_RESPONSE_BYTES,
    UPSTREAM_TIMEOUT,
    json_env,
)

# Where the upstream credential travels, from the spec's security scheme
# (config.py). Auth mode 'passthrough' forwards the caller's Authorization
# header as such, whatever the spec declares, so it always carries a bearer
# token; env-token and api-key present the configured value in the header or
# query parameter the API expects.
CREDENTIAL_IN_QUERY = AUTH_MODE != "passthrough" and CREDENTIAL_LOCATION == "query"
CREDENTIAL_HEADER = "Authorization" if AUTH_MODE == "passthrough" else CREDENTIAL_NAME
CREDENTIAL_WHERE = (
    f"{CREDENTIAL_NAME} query parameter" if CREDENTIAL_IN_QUERY else f"{CREDENTIAL_HEADER} header"
)
CREDENTIAL_EXAMPLE = (
    "'Bearer <your API token>'"
    if not CREDENTIAL_IN_QUERY and CREDENTIAL_HEADER.lower() == "authorization"
    else "'<your API key>'"
)


@dataclass(frozen=True)
class Route:
    """One upstream HTTP operation and where each argument travels."""

    method: str
    path: str
    path_params: tuple[str, ...] = ()
    query_params: tuple[str, ...] = ()
    body_params: tuple[str, ...] = ()
    raw_body: str | None = None
    required: tuple[str, ...] = ()
    form: bool = False
    nulls: tuple[str, ...] = ()  # body arguments whose None is sent as JSON null
    aliases: dict[str, str] | None = None  # tool argument name -> wire name
    base_url: str | None = None  # the operation's own server; MCPCAST_BASE_URL overrides it

    def wire(self, name: str) -> str:
        return (self.aliases or {}).get(name, name)


def select_route(routes: tuple[Route, ...], args: dict[str, Any], hint: str | None = None) -> Route:
    """First route (in plan order) whose required arguments were all supplied.

    Raises:
        ToolError: ``VALIDATION_ERROR`` when no route's requirements are met —
            the call is never sent to some route with its arguments missing.
            *hint* names the alternatives as the agent knows them.
    """
    provided = {name for name, value in args.items() if value is not None}
    for route in routes:
        if set(route.required) <= provided | set(route.nulls):
            return route
    alternatives = hint or " | ".join(" + ".join(r.required) or "(no parameters)" for r in routes)
    raise ToolError(
        f"No route of this tool has its required arguments. Provide one of: {alternatives}",
        code="VALIDATION_ERROR",
    )


Handler = TypeVar("Handler", bound=Callable[..., Any])


def advertise(schemas: dict[str, dict[str, Any]]) -> Callable[[Handler], Handler]:
    """Advertise each parameter's JSON Schema from the plan in the tool's input schema.

    The handler's annotations carry the base type the server validates
    (``str``, ``int``, ``list[Any]``); *schemas* — one per parameter, keyed
    by its Python name — is what MCP clients and agents read in tools/list:
    enums, bounds, lengths, patterns, formats, defaults and descriptions.
    The API stays the authority on those constraints and rejects what
    breaks them. Apply it below ``@server.tool``, which reads the schema.

    Raises:
        TypeError: When *schemas* names a parameter the handler does not have.
    """

    def apply(handler: Handler) -> Handler:
        hints = get_type_hints(handler)
        for name, schema in schemas.items():
            if name not in hints:
                raise TypeError(f"{handler.__name__}() has no parameter {name!r}")
            metadata = Field(json_schema_extra=_replace_with(schema))
            handler.__annotations__[name] = Annotated[hints[name], metadata]
        return handler

    return apply


def _replace_with(schema: dict[str, Any]) -> Callable[[dict[str, Any]], None]:
    """A ``json_schema_extra`` hook that swaps the generated field schema for *schema*."""

    def replace(generated: dict[str, Any]) -> None:
        generated.clear()
        generated.update(copy.deepcopy(schema))

    return replace


def header(ctx: RequestContext, name: str) -> str | None:
    """A request header (MCP ``meta``) by case-insensitive name."""
    for key, value in (ctx.meta or {}).items():
        if str(key).lower() == name:
            return str(value)
    return None


def is_loopback(host: str) -> bool:
    """True for localhost and loopback addresses."""
    if host in ("localhost", "ip6-localhost"):
        return True
    try:
        return ipaddress.ip_address(host.strip("[]")).is_loopback
    except ValueError:
        return False


def credential(value: str, source: str) -> str:
    """*value* as the upstream credential, validated without ever echoing it.

    Raises:
        ToolError: ``UPSTREAM_AUTH_INVALID`` for a control or non-ASCII
            character (a trailing newline from ``echo``, a pasted quote…) —
            the transport would reject it, and its error text would carry the
            secret — and for a ``<placeholder>`` copied from .env.example.
    """
    token = value.strip()
    if any(not 0x20 <= ord(ch) <= 0x7E for ch in token):
        raise ToolError(
            f"{source} contains a control or non-ASCII character; set it to the exact "
            f"{CREDENTIAL_WHERE} value, e.g. {CREDENTIAL_EXAMPLE}",
            code="UPSTREAM_AUTH_INVALID",
        )
    if "<" in token or ">" in token:
        raise ToolError(
            f"{source} still holds a placeholder (<...>); set it to the real "
            f"{CREDENTIAL_WHERE} value",
            code="UPSTREAM_AUTH_INVALID",
        )
    return token


def redact(text: str, secret: str) -> str:
    """*text* with *secret* — and the token after its scheme — replaced by ``[redacted]``.

    An upstream that quotes the credential it received (a debug error page,
    ``Invalid API key: Bearer …``) must not hand it to the MCP client, so
    every body is scrubbed before it is excerpted or returned. The bare
    token is replaced as well as the full value, and so is its URL-encoded
    form (a query-string credential echoed from the request line). Tokens
    shorter than eight characters are left alone: replacing them would blank
    unrelated text far more often than it would hide a secret.
    """
    token = secret.split(" ", 1)[-1]
    if len(token) < 8:
        return text
    for needle in dict.fromkeys((secret, token, quote(token, safe=""))):
        text = text.replace(needle, "[redacted]")
    return text


def _flatten(prefix: str, value: Any, out: list[tuple[str, str]]) -> None:
    """Bracket-notation encoding for nested form/query values (``a[b][0]=v``)."""
    if isinstance(value, dict):
        for key, item in value.items():
            _flatten(f"{prefix}[{key}]", item, out)
    elif isinstance(value, (list, tuple)):
        for index, item in enumerate(value):
            _flatten(f"{prefix}[{index}]", item, out)
    elif isinstance(value, bool):
        out.append((prefix, "true" if value else "false"))
    elif value is not None:
        out.append((prefix, str(value)))


def _query_pairs(query: dict[str, Any]) -> list[tuple[str, str]]:
    """Query encoding: scalars as-is, arrays repeated, objects in deepObject style.

    An array of objects (or of arrays) is indexed — ``tags[0][a]=1&tags[1][a]=2``
    — so every element keeps its own slot; a scalar array is repeated.
    """
    pairs: list[tuple[str, str]] = []
    for key, value in query.items():
        if isinstance(value, dict):
            _flatten(key, value, pairs)
        elif isinstance(value, (list, tuple)):
            for index, item in enumerate(value):
                if isinstance(item, (dict, list, tuple)):
                    _flatten(f"{key}[{index}]", item, pairs)
                elif isinstance(item, bool):
                    pairs.append((key, "true" if item else "false"))
                elif item is not None:
                    pairs.append((key, str(item)))
        elif isinstance(value, bool):
            pairs.append((key, "true" if value else "false"))
        elif value is not None:
            pairs.append((key, str(value)))
    return pairs


class Upstream:
    """Executes routes against the upstream API using the configured auth mode.

    One ``httpx.AsyncClient`` is opened on first use and reused for every
    call (connection pooling); ``build_server()`` closes it in a shutdown
    hook. Tests and evaluations inject their own client instead.
    """

    def __init__(self, client: httpx.AsyncClient | None = None) -> None:
        self._client = client
        self._owned: httpx.AsyncClient | None = None

    def client(self) -> httpx.AsyncClient:
        """The injected client, else one opened lazily and kept."""
        if self._client is not None:
            return self._client
        if self._owned is None:
            self._owned = httpx.AsyncClient(timeout=UPSTREAM_TIMEOUT)
        return self._owned

    async def aclose(self) -> None:
        """Close the client this instance opened (an injected one belongs to its owner)."""
        if self._owned is not None:
            await self._owned.aclose()
            self._owned = None

    def _credential(self, ctx: RequestContext) -> str:
        """The upstream credential for this call under AUTH_MODE ('' under 'none')."""
        if AUTH_MODE == "passthrough":
            token = header(ctx, "authorization")
            if not token:
                raise ToolError(
                    "The MCP request carried no Authorization header. Auth mode "
                    "'passthrough' forwards the caller's bearer token to the upstream "
                    "API: connect over HTTP/SSE with an Authorization header. For a "
                    "personal server over stdio (Claude Desktop, Claude Code, Cursor) "
                    "regenerate with --auth env-token and set MCPCAST_UPSTREAM_TOKEN.",
                    code="UPSTREAM_AUTH_MISSING",
                )
            token = credential(token, "The Authorization header")
            if not token.startswith("Bearer "):
                raise ToolError(
                    "The Authorization header must carry a bearer token ('Bearer <token>'); "
                    "auth mode 'passthrough' forwards nothing else to the upstream API.",
                    code="UPSTREAM_AUTH_MISSING",
                )
            return token
        if AUTH_MODE == "env-token":
            token = credential(
                os.environ.get("MCPCAST_UPSTREAM_TOKEN", ""), "MCPCAST_UPSTREAM_TOKEN"
            )
            if not token:
                raise ToolError(
                    "MCPCAST_UPSTREAM_TOKEN is not set. Auth mode 'env-token' presents "
                    f"that value as the {CREDENTIAL_WHERE} on every upstream call, "
                    f"e.g. MCPCAST_UPSTREAM_TOKEN={CREDENTIAL_EXAMPLE}.",
                    code="UPSTREAM_AUTH_MISSING",
                )
            return token
        if AUTH_MODE == "api-key":
            tenant = getattr(ctx.client, "tenant_id", None)
            # tenant id -> upstream credential, read per call so rotated
            # credentials apply without a restart.
            raw = json_env("MCPCAST_UPSTREAM_TOKENS").get(tenant or "")
            token = credential(str(raw), f"MCPCAST_UPSTREAM_TOKENS[{tenant!r}]") if raw else ""
            if not token:
                raise ToolError(
                    f"No upstream credential configured for tenant {tenant!r}; "
                    "set MCPCAST_UPSTREAM_TOKENS to a JSON object of tenant -> "
                    f"{CREDENTIAL_WHERE} value.",
                    code="UPSTREAM_AUTH_MISSING",
                )
            return token
        return ""

    async def call(self, route: Route, args: dict[str, Any], ctx: RequestContext) -> Any:
        """Send one request for *route* and return the decoded response.

        The credential travels where the spec's security scheme puts it: the
        CREDENTIAL_NAME header, or the CREDENTIAL_NAME query parameter (auth
        mode 'passthrough' always forwards the caller's Authorization header).
        A body is sent whenever the route declares body parameters and the
        agent supplied any — on GET too, for search-style operations — never
        on HEAD.

        The whole exchange — connecting, sending, waiting for the status line
        and reading the body — must finish within UPSTREAM_TIMEOUT seconds
        (MCPCAST_TIMEOUT), on top of httpx's own timeout per network
        operation: a peer that trickles bytes cannot hold the call (and its
        buffer) open for longer.

        Raises:
            ToolError: ``UPSTREAM_TIMEOUT`` (retryable) when the deadline
                elapses, ``UPSTREAM_UNREACHABLE`` (retryable) for any other
                transport failure — never quoting the request or the
                exception text, which may carry the credential.
        """
        base = BASE_URL or route.base_url or DEFAULT_BASE_URL
        url = base.rstrip("/") + route.path
        for name in route.path_params:
            value = args.get(name)
            if value is None:
                raise ToolError(f"Missing required parameter {name!r}", code="VALIDATION_ERROR")
            segment = str(value)
            # A single, real path segment only: an empty value or a dot segment
            # would resolve to a different endpoint than the one this tool exposes.
            if segment in ("", ".", "..") or any(ord(ch) < 32 for ch in segment):
                raise ToolError(
                    f"Invalid value for path parameter {name!r}: {segment!r}",
                    code="VALIDATION_ERROR",
                )
            url = url.replace("{" + route.wire(name) + "}", quote(segment, safe=""))
        secret = self._credential(ctx)
        _refuse_plaintext_credential(url, secret)
        query = {route.wire(k): args[k] for k in route.query_params if args.get(k) is not None}
        params = _query_pairs(query)
        headers: dict[str, str] = {}
        if secret and CREDENTIAL_IN_QUERY:
            params.append((CREDENTIAL_NAME, secret))
        elif secret:
            headers[CREDENTIAL_HEADER] = secret
        payload: Any = None
        if route.raw_body is not None:
            payload = args.get(route.raw_body)
        elif route.body_params:
            payload = {
                route.wire(k): args.get(k)
                for k in route.body_params
                if args.get(k) is not None or k in route.nulls
            }
        kwargs: dict[str, Any] = {"params": params, "headers": headers}
        if payload is not None and route.method != "HEAD":
            if route.form:
                pairs: list[tuple[str, str]] = []
                if isinstance(payload, dict):
                    for key, value in payload.items():
                        _flatten(key, value, pairs)
                else:
                    _flatten("body", payload, pairs)
                kwargs["data"] = dict(pairs)
            else:
                kwargs["json"] = payload

        try:
            status, content_type, retry_after, encoding, body = await asyncio.wait_for(
                self._exchange(route, url, kwargs), timeout=UPSTREAM_TIMEOUT
            )
        except (asyncio.TimeoutError, TimeoutError, httpx.TimeoutException) as exc:
            raise ToolError(
                f"{route.method} {route.path} did not complete within {UPSTREAM_TIMEOUT:g}s "
                "(MCPCAST_TIMEOUT)",
                code="UPSTREAM_TIMEOUT",
                retryable=True,
                details={"timeout": UPSTREAM_TIMEOUT},
            ) from exc
        except httpx.HTTPError as exc:
            # Never the exception text: for a rejected header it quotes the credential.
            raise ToolError(
                f"{route.method} {route.path} failed: {type(exc).__name__}",
                code="UPSTREAM_UNREACHABLE",
                retryable=True,
            ) from exc

        # Scrubbed before anything is cut or parsed: a token straddling the
        # excerpt boundary would otherwise leak in part.
        text = redact(body.decode(encoding, errors="replace"), secret)
        if status >= 400:
            details: dict[str, Any] = {"status": status}
            if retry_after:
                details["retry_after"] = retry_after
            excerpt = text[:ERROR_EXCERPT_CHARS]
            raise ToolError(
                f"{route.method} {route.path} returned HTTP {status}"
                + (f": {excerpt}" if excerpt else ""),
                code="UPSTREAM_ERROR",
                retryable=status >= 500 or status in (408, 425, 429),
                details=details,
            )
        if not body:
            return {"status": status}
        if "json" in content_type:
            try:
                return json.loads(text)
            except ValueError as exc:
                raise ToolError(
                    f"{route.method} {route.path} returned a body that is not JSON although "
                    f"its content type is {content_type!r}",
                    code="UPSTREAM_ERROR",
                    details={"status": status},
                ) from exc
        return {"status": status, "body": text}

    async def _exchange(
        self, route: Route, url: str, kwargs: dict[str, Any]
    ) -> tuple[int, str, str | None, str, bytes]:
        """One request: ``(status, content type, retry-after, encoding, capped body)``."""
        async with self.client().stream(route.method, url, **kwargs) as response:
            return (
                response.status_code,
                response.headers.get("content-type", ""),
                response.headers.get("retry-after"),
                response.encoding or "utf-8",
                await _read_capped(response, route),
            )


async def _read_capped(response: httpx.Response, route: Route) -> bytes:
    """The response body, refusing more than MAX_RESPONSE_BYTES before buffering it."""

    def too_large(size: int | None) -> ToolError:
        return ToolError(
            f"{route.method} {route.path} returned more than {MAX_RESPONSE_BYTES} bytes"
            + (f" ({size} announced)" if size else "")
            + "; narrow the request or raise MCPCAST_MAX_RESPONSE_BYTES",
            code="UPSTREAM_RESPONSE_TOO_LARGE",
            details={"status": response.status_code, "limit": MAX_RESPONSE_BYTES},
        )

    declared = response.headers.get("content-length", "")
    if declared.isdigit() and int(declared) > MAX_RESPONSE_BYTES:
        raise too_large(int(declared))
    chunks: list[bytes] = []
    received = 0
    async for chunk in response.aiter_bytes():
        received += len(chunk)
        if received > MAX_RESPONSE_BYTES:
            raise too_large(None)
        chunks.append(chunk)
    return b"".join(chunks)


def _refuse_plaintext_credential(url: str, secret: str) -> None:
    """A credential travels to a non-loopback host over https only (or by explicit opt-in).

    Header or query parameter alike: a query-string credential on plain http
    is the more exposed of the two (it lands in proxy and server logs).
    """
    if not secret or ALLOW_INSECURE_HTTP:
        return
    parts = urlsplit(url)
    host = parts.hostname or ""
    if parts.scheme != "https" and not is_loopback(host):
        raise ToolError(
            f"Refusing to send the upstream credential over plain http to {host!r}; use an "
            "https base URL, or set MCPCAST_ALLOW_INSECURE_HTTP=1 to accept the risk.",
            code="UPSTREAM_INSECURE",
        )
