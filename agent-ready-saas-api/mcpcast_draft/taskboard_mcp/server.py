"""Assembly of the taskboard MCP server: authentication, the approval gate, every tool.

Generated by `promptise mcpcast` from openapi.json (profile full, auth api-key).
Regenerate after editing mcpcast.plan.yaml:

    promptise mcpcast mcpcast.plan.yaml

build_server() is the one place the pieces meet; evaluations and tests pass
an approval handler or an httpx client to it instead of patching modules.
"""

from __future__ import annotations

from typing import Any

import httpx
from promptise.mcp.server import APIKeyAuth, AuthMiddleware, MCPServer

from .approval import install_approval_gate
from .config import EXAMPLE_CLIENT_KEYS, INSTRUCTIONS, SERVER_NAME, SERVER_VERSION, json_env
from .tools import register_all
from .upstream import Upstream


def build_server(
    *,
    approval_handler: Any | None = None,
    http_client: httpx.AsyncClient | None = None,
) -> MCPServer:
    """Build the MCP server.

    Args:
        approval_handler: Override the approver for gated tools (evaluations
            and tests inject an auto-approver here).
        http_client: Override the upstream HTTP client (evaluations inject a
            mock transport for write/destructive tools).

    Raises:
        RuntimeError: When MCPCAST_CLIENT_KEYS names no client key — the server
            would silently reject every request — or a placeholder one: a key
            still holding <...> from .env.example, or a key copied from the
            documentation (sk-acme, sk-reviewer), which anyone can read.
    """
    server = MCPServer(
        name=SERVER_NAME,
        version=SERVER_VERSION,
        instructions=INSTRUCTIONS,
        require_tenant=True,
    )
    # MCP clients authenticate with an API key; each key names a tenant whose
    # upstream credential lives in MCPCAST_UPSTREAM_TOKENS. Reviewers carry the
    # 'approver' role on their key. Keys are read here, once: rotating them
    # needs a restart.
    keys = json_env("MCPCAST_CLIENT_KEYS")
    if not keys:
        raise RuntimeError(
            "MCPCAST_CLIENT_KEYS is empty: auth mode 'api-key' needs at least one client "
            "key (a JSON object: key -> {client_id, tenant_id, roles}); without one the "
            "server would reject every request"
        )
    # A key from the documentation is public, and a <placeholder> was never
    # filled in: neither may open the server. The refusal names neither value.
    if any(key in EXAMPLE_CLIENT_KEYS or "<" in key or ">" in key for key in keys):
        raise RuntimeError(
            "MCPCAST_CLIENT_KEYS holds a placeholder or documentation key (one containing "
            "'<' or '>', or sk-acme / sk-reviewer from the README): every client key must "
            "be a secret of your own — mint one with "
            "python -c 'import secrets; print(\"sk-\" + secrets.token_urlsafe(32))'"
        )
    server.add_middleware(AuthMiddleware(APIKeyAuth(keys=keys)))
    install_approval_gate(server, approval_handler)
    upstream = Upstream(http_client)
    server.on_shutdown(upstream.aclose)
    register_all(server, upstream)
    return server
