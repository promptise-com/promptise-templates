def _base_url_from_env() -> str | None:
    """MCPCAST_BASE_URL, refused unless it is one clean URL — without echoing it.

    Route paths are appended to it and every credential goes to its host, so
    it may carry no whitespace or control character (a second line in a file
    read line by line), no userinfo (user:password@ — the server authenticates
    with its own variables) and no query string or fragment (a key passed
    there would be dropped from every request, or copied into a log). The
    refusal names the rule, never the value, which may be a secret.
    """
    value = os.environ.get("MCPCAST_BASE_URL", "").strip().rstrip("/")
    if not value:
        return None
    if any(ch.isspace() or ord(ch) < 0x20 or ord(ch) == 0x7F for ch in value):
        raise RuntimeError("MCPCAST_BASE_URL contains whitespace or a control character")
    parts = urlsplit(value)
    if parts.scheme not in ("http", "https") or not parts.netloc:
        raise RuntimeError("MCPCAST_BASE_URL must be an absolute http:// or https:// URL")
    if "@" in parts.netloc:
        raise RuntimeError(
            "MCPCAST_BASE_URL must not carry credentials (user:password@); the server "
            "authenticates with MCPCAST_UPSTREAM_TOKEN or MCPCAST_UPSTREAM_TOKENS instead"
        )
    if parts.query or parts.fragment:
        raise RuntimeError(
            "MCPCAST_BASE_URL must not carry a query string or fragment: route paths are "
            "appended to it, so the query would be dropped from every request — pass "
            "query parameters through the tools' own arguments"
        )
    return value


